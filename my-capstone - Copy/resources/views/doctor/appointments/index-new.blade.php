        // Global callback triggered by FullCalendar date changes
        window.onCalendarDateChange = function(dateStr) {
            renderRightSidebar(dateStr);
            
            // Sync the mini calendar highlight to match the visible date
            const parsedDate = new Date(dateStr);
            const targetYear = parsedDate.getFullYear();
            const targetMonth = parsedDate.getMonth();
            const targetDay = parsedDate.getDate();
            
            if (targetYear !== currentCalendarYear || targetMonth !== currentCalendarMonth) {
                currentCalendarYear = targetYear;
                currentCalendarMonth = targetMonth;
                generateMiniCalendar(currentCalendarYear, currentCalendarMonth);
                updateMonthYearSelect();
            }
            
            // Highlight active day in the mini grid
            document.querySelectorAll('#calendar-days button').forEach(btn => {
                btn.style.border = 'none';
                if (parseInt(btn.textContent) === targetDay && !btn.style.color.includes('D1D5DB')) {
                    btn.style.border = '2px solid #14B8A6';
                }
            });
        };

        // Mini calendar generation
        function generateMiniCalendar(year = null, month = null) {
            const today = new Date();
            const currentYear = year || today.getFullYear();
            const currentMonth = month !== null ? month : today.getMonth();
            
            const firstDay = new Date(currentYear, currentMonth, 1).getDay();
            const daysInMonth = new Date(currentYear, currentMonth + 1, 0).getDate();
            const lastDayPrevMonth = new Date(currentYear, currentMonth, 0).getDate();
            
            const calendarDays = document.getElementById('calendar-days');
            const monthLabel = document.getElementById('calendar-month-label');
            
            // Update month label
            const monthNames = ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'];
            monthLabel.textContent = monthNames[currentMonth];
            
            calendarDays.innerHTML = '';
            
            // Previous month's trailing days (grayed out)
            for (let i = firstDay - 1; i >= 0; i--) {
                const dayCell = document.createElement('button');
                dayCell.style.cssText = 'width: 32px; height: 32px; display: flex; align-items: center; justify-content: center; font-size: 0.875rem; color: #D1D5DB; border-radius: 9999px; transition: all 0.2s;';
                dayCell.textContent = lastDayPrevMonth - i;
                dayCell.onmouseover = function() { this.style.backgroundColor = '#F9FAFB'; };
                dayCell.onmouseout = function() { this.style.backgroundColor = 'transparent'; };
                calendarDays.appendChild(dayCell);
            }
            
            // Current month days
            for (let day = 1; day <= daysInMonth; day++) {
                const dayCell = document.createElement('button');
                const isToday = (day === today.getDate() && currentMonth === today.getMonth() && currentYear === today.getFullYear());
                
                if (isToday) {
                    // Today - highlighted with teal circle
                    dayCell.style.cssText = 'width: 32px; height: 32px; display: flex; align-items: center; justify-content: center; font-size: 0.875rem; font-weight: bold; background-color: #14B8A6; color: white; border-radius: 9999px; transition: all 0.2s;';
                    dayCell.onmouseover = function() { this.style.backgroundColor = '#0D9488'; };
                    dayCell.onmouseout = function() { this.style.backgroundColor = '#14B8A6'; };
                } else {
                    // Regular day
                    dayCell.style.cssText = 'width: 32px; height: 32px; display: flex; align-items: center; justify-content: center; font-size: 0.875rem; color: #374151; border-radius: 9999px; transition: all 0.2s;';
                    dayCell.onmouseover = function() { this.style.backgroundColor = '#F3F4F6'; };
                    dayCell.onmouseout = function() { this.style.backgroundColor = 'transparent'; };
                }
                
                dayCell.textContent = day;
                dayCell.onclick = function() {
                    const selectedDate = new Date(currentYear, currentMonth, day);
                    const dateStr = getLocalDateString(selectedDate);
                    renderRightSidebar(dateStr);
                    
                    // Highlight selected day on mini calendar
                    document.querySelectorAll('#calendar-days button').forEach(btn => {
                        btn.style.border = 'none';
                    });
                    dayCell.style.border = '2px solid #14B8A6';
                };
                
                calendarDays.appendChild(dayCell);
            }
            
            // Next month's leading days (grayed out)
            const totalCells = calendarDays.children.length;
            const remainingCells = 42 - totalCells; // 6 rows × 7 days = 42 cells
            for (let day = 1; day <= remainingCells && remainingCells < 7; day++) {
                const dayCell = document.createElement('button');
                dayCell.style.cssText = 'width: 32px; height: 32px; display: flex; align-items: center; justify-content: center; font-size: 0.875rem; color: #D1D5DB; border-radius: 9999px; transition: all 0.2s;';
                dayCell.textContent = day;
                dayCell.onmouseover = function() { this.style.backgroundColor = '#F9FAFB'; };
                dayCell.onmouseout = function() { this.style.backgroundColor = 'transparent'; };
                calendarDays.appendChild(dayCell);
            }
        }

        // Calendar navigation
        let currentCalendarYear = new Date().getFullYear();
        let currentCalendarMonth = new Date().getMonth();

        document.getElementById('prev-month')?.addEventListener('click', function() {
            currentCalendarMonth--;
            if (currentCalendarMonth < 0) {
                currentCalendarMonth = 11;
                currentCalendarYear--;
            }
            generateMiniCalendar(currentCalendarYear, currentCalendarMonth);
            updateMonthYearSelect();
        });

        document.getElementById('next-month')?.addEventListener('click', function() {
            currentCalendarMonth++;
            if (currentCalendarMonth > 11) {
                currentCalendarMonth = 0;
                currentCalendarYear++;
            }
            generateMiniCalendar(currentCalendarYear, currentCalendarMonth);
            updateMonthYearSelect();
        });

        document.getElementById('today-btn')?.addEventListener('click', function() {
            const today = new Date();
            currentCalendarYear = today.getFullYear();
            currentCalendarMonth = today.getMonth();
            generateMiniCalendar(currentCalendarYear, currentCalendarMonth);
            updateMonthYearSelect();
        });

        document.getElementById('month-year-select')?.addEventListener('change', function() {
            const [year, month] = this.value.split('-');
            currentCalendarYear = parseInt(year);
            currentCalendarMonth = parseInt(month) - 1;
            generateMiniCalendar(currentCalendarYear, currentCalendarMonth);
        });

        function updateMonthYearSelect() {
            const select = document.getElementById('month-year-select');
            if (select) {
                const value = `${currentCalendarYear}-${String(currentCalendarMonth + 1).padStart(2, '0')}`;
                select.value = value;
            }
        }

        // Appointment actions
        function approveAppointment(id) {
            if (confirm('Approve this appointment?')) {
                fetch(`/doctor/appointments/${id}/approve`, {
                    method: 'POST',
                    headers: {
                        'X-CSRF-TOKEN': document.querySelector('meta[name="csrf-token"]').content,
                        'Content-Type': 'application/json'
                    }
                }).then(() => location.reload());
            }
        }

        // Decline / Cancel
        function declineAppointment(id) {
            if (confirm('Decline this appointment?')) {
                fetch(`/doctor/appointments/${id}/decline`, {
                    method: 'POST',
                    headers: {
                        'X-CSRF-TOKEN': document.querySelector('meta[name="csrf-token"]').content,
                        'Content-Type': 'application/json'
                    }
                }).then(() => location.reload());
            }
        }

        // Check in patient
        function checkInPatient(id) {
            fetch(`/doctor/appointments/${id}/check-in`, {
                method: 'POST',
                headers: {
                    'X-CSRF-TOKEN': document.querySelector('meta[name="csrf-token"]').content,
                    'Content-Type': 'application/json'
                }
            }).then(res => res.json())
              .then(data => {
                  if (data.success) {
                      // Fetch updated appointments globally or simply reload
                      location.reload();
                  }
              });
        }

        // Start consultation bypass
        function startConsultation(appointmentId) {
            window.location.href = `/doctor/appointments/${appointmentId}/start-consultation`;
        }

        // Initialize on DOM ready
        document.addEventListener('DOMContentLoaded', function() {
            generateMiniCalendar();
            updateMonthYearSelect();
            
            // Initial sidebar render for today
            const todayStr = getLocalDateString(new Date());
            renderRightSidebar(todayStr);
        });
